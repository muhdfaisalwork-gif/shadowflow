<#
.SYNOPSIS
    mix_presentation_audio.ps1
    Concatenates slide narration clips, mixes with background music, applies sidechain ducking,
    and normalizes loudness using FFmpeg.

.DESCRIPTION
    Takes the timeline.json produced by generate_tts_narration.py, merges speech tracks,
    and ducks background music beneath the speaker. Can also multiplex directly into video slides.

.PARAMETER TimelinePath
    Path to timeline.json generated by generate_tts_narration.py (Default: output/audio/timeline.json)

.PARAMETER BackgroundMusic
    Path to background music audio file. If omitted, generates speech-only master track.

.PARAMETER OutputAudio
    Path for the mixed audio track (Default: output/presentation_mixed_audio.aac)

.PARAMETER OutputVideo
    Optional path to render a video file if video/slides are provided.
#>

[CmdletBinding()]
param (
    [string]$TimelinePath = "output/audio/timeline.json",
    [string]$BackgroundMusic = "",
    [string]$OutputAudio = "output/presentation_mixed_audio.aac",
    [string]$OutputVideo = ""
)

Write-Host "=== SHADOWFLOW PRESENTATION AUDIO MIXER ===" -ForegroundColor Cyan

if (-not (Test-Path $TimelinePath)) {
    Write-Error "Timeline file not found at: $TimelinePath"
    exit 1
}

$timelineJson = Get-Content -Raw $TimelinePath | ConvertFrom-Json
$slides = $timelineJson.timeline
$totalSeconds = $timelineJson.total_video_duration_seconds

Write-Host "Loaded $($slides.Count) slides. Total target duration: $($totalSeconds)s" -ForegroundColor Green

# 1. Create a concat list for FFmpeg to assemble the continuous voiceover
$audioDir = (Resolve-Path (Split-Path $TimelinePath)).Path
$concatListPath = Join-Path $audioDir "voiceover_concat.txt"
$concatLines = @()

foreach ($s in $slides) {
    $resolvedAudioPath = (Resolve-Path $s.audio_path).Path.Replace("\", "/")
    $concatLines += "file '$resolvedAudioPath'"
    
    # Calculate pause duration after slide speech
    $pauseSeconds = [math]::Round(($s.total_duration_seconds - $s.speech_duration_seconds), 3)
    if ($pauseSeconds -gt 0.05) {
        $silenceName = "silence_$([int]($pauseSeconds * 1000))ms.mp3"
        $silencePath = Join-Path $audioDir $silenceName
        if (-not (Test-Path $silencePath)) {
            & ffmpeg -v error -f lavfi -i "anullsrc=r=24000:cl=mono" -t $pauseSeconds -q:a 9 -acodec libmp3lame $silencePath -y
        }
        $resolvedSilencePath = (Resolve-Path $silencePath).Path.Replace("\", "/")
        $concatLines += "file '$resolvedSilencePath'"
    }
}

$concatLines | Set-Content -Path $concatListPath -Encoding Ascii
Write-Host "Generated voiceover assembly list: $concatListPath" -ForegroundColor DarkGray

# 2. Render unified voiceover track
$voiceoverMaster = Join-Path $audioDir "master_voiceover.aac"
Write-Host "Merging speech tracks with micro-pauses..." -ForegroundColor Yellow
& ffmpeg -v error -f concat -safe 0 -i $concatListPath -c:a aac -b:a 192k $voiceoverMaster -y

if (-not (Test-Path $voiceoverMaster)) {
    Write-Error "Failed to produce master voiceover track."
    exit 1
}

# 3. Mix with Background Music and apply Sidechain Ducking
$outputAbsPath = [System.IO.Path]::GetFullPath($OutputAudio)
$outputDir = Split-Path $outputAbsPath
if ($outputDir -and -not (Test-Path $outputDir)) {
    New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
}

if ($BackgroundMusic -and (Test-Path $BackgroundMusic)) {
    Write-Host "Applying Sidechain Ducking with music: $BackgroundMusic..." -ForegroundColor Yellow
    
    # Filter Complex Explanation:
    # [1:a] Background music attenuated to baseline volume (0.30)
    # sidechaincompress lowers music by ~14dB when speech [0:a] is above threshold
    # amix combines the clean voiceover and ducked music
    # loudnorm normalizes speech and music to -16 LUFS (web broadcast standard)
    $filterComplex = "[1:a]volume=0.30,aloop=loop=-1:size=2e+09[bgm_looped]; " + `
                     "[bgm_looped][0:a]sidechaincompress=threshold=0.08:ratio=5:attack=40:release=350[ducked_bgm]; " + `
                     "[0:a][ducked_bgm]amix=inputs=2:duration=first:dropout_transition=2,loudnorm=I=-16:TP=-1.5:LRA=11[aout]"

    & ffmpeg -i $voiceoverMaster -i $BackgroundMusic -filter_complex $filterComplex -map "[aout]" -c:a aac -b:a 256k $outputAbsPath -y
} else {
    Write-Host "No background music provided. Applying loudness normalization to voiceover..." -ForegroundColor Yellow
    & ffmpeg -i $voiceoverMaster -af "loudnorm=I=-16:TP=-1.5:LRA=11" -c:a aac -b:a 192k $outputAbsPath -y
}

if (Test-Path $outputAbsPath) {
    Write-Host "[SUCCESS] Master presentation audio exported to: $outputAbsPath" -ForegroundColor Green
} else {
    Write-Error "Failed to create mixed output audio."
    exit 1
}

# 4. Optional video multiplexing
if ($OutputVideo) {
    Write-Host "Multiplexing into target video: $OutputVideo" -ForegroundColor Yellow
    if (Test-Path $OutputVideo) {
        $tempVideo = $OutputVideo + ".tmp.mp4"
        & ffmpeg -i $OutputVideo -i $outputAbsPath -c:v copy -c:a aac -map 0:v:0 -map 1:a:0 -shortest $tempVideo -y
        Move-Item -Path $tempVideo -Destination $OutputVideo -Force
        Write-Host "[SUCCESS] Updated video with synchronized audio: $OutputVideo" -ForegroundColor Green
    }
}

Write-Host "=== MIXING WORKFLOW COMPLETE ===" -ForegroundColor Cyan
